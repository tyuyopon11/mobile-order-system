create table if not exists public.order_number_counters (
  auction_date date primary key,
  last_value integer not null default 0
    check (last_value >= 0 and last_value <= 9999),
  updated_at timestamptz not null default now()
);

revoke all on table public.order_number_counters from anon, authenticated;

create or replace function public.next_lei_port_order_number(
  p_auction_date date
)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  next_value integer;
begin
  if p_auction_date is null then
    raise exception 'auction_date is required';
  end if;

  insert into public.order_number_counters (
    auction_date,
    last_value,
    updated_at
  )
  values (p_auction_date, 1, now())
  on conflict (auction_date)
  do update set
    last_value = public.order_number_counters.last_value + 1,
    updated_at = now()
  returning last_value into next_value;

  if next_value > 9999 then
    raise exception 'daily order number limit exceeded for %', p_auction_date;
  end if;

  return
    'LP' ||
    to_char(p_auction_date, 'YYMMDD') ||
    lpad(next_value::text, 4, '0');
end;
$$;

revoke all on function public.next_lei_port_order_number(date) from public;
grant execute on function public.next_lei_port_order_number(date)
  to authenticated;

