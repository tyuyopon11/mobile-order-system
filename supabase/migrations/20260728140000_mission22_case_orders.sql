create table if not exists public.favorite_shops (
  user_id uuid not null references auth.users(id) on delete cascade,
  shop_id uuid not null references public.shops(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, shop_id)
);

alter table public.favorite_shops enable row level security;

drop policy if exists "buyers manage own favorite shops" on public.favorite_shops;
create policy "buyers manage own favorite shops"
  on public.favorite_shops
  for all
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

create table if not exists public.order_email_notifications (
